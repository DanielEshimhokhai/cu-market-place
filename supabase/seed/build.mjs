// Generates supabase/seed.sql from data.mjs. Deterministic: same input → same output.
// Run: npm run seed:build
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import {
  DEMO_DOMAIN, categories, locations, HOURS, buyers, IMG, businesses, ownerNames, reviewTexts, mixedReviewTexts, conversationScripts,
} from "./data.mjs";

// ── helpers ─────────────────────────────────────────────────────────
function uuidFrom(key) {
  const h = createHash("sha1").update("cu-marketplace:" + key).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString("hex");
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}
function mulberry32(a) {
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(20261001);
const int = (min, max) => min + Math.floor(rand() * (max - min + 1));
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
const chance = (p) => rand() < p;

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? "true" : "false");
const ago = (minutes) => `now() - interval '${Math.max(0, Math.round(minutes))} minutes'`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const catRef = (slug) => `(select id from public.categories where slug = ${q(slug)})`;
const locRef = (slug) => `(select id from public.locations where slug = ${q(slug)})`;
const imageUrl = (key) => `https://images.unsplash.com/photo-${IMG[key]}?w=900&q=70&auto=format&fit=crop`;
const titleCase = (local) => local.split(".").map((s) => s[0].toUpperCase() + s.slice(1)).join(" ");
const email = (local) => `${local}@${DEMO_DOMAIN}`;
const DAY = 24 * 60;

const out = [];
const emit = (s) => out.push(s);
function insert(table, cols, rows) {
  if (!rows.length) return;
  for (let i = 0; i < rows.length; i += 200) {
    const chunk = rows.slice(i, i + 200);
    emit(`insert into ${table} (${cols.join(", ")}) values\n  ${chunk.map((r) => `(${r.join(", ")})`).join(",\n  ")};`);
  }
}

// ── reference data ──────────────────────────────────────────────────
emit("-- Generated by supabase/seed/build.mjs — do not edit by hand.");
emit("-- Demo rows are flagged is_demo = true. Remove them with supabase/remove_demo.sql.");
emit("begin;");
insert("public.categories", ["slug", "name", "kind", "sort"], categories.map(([slug, name, kind], i) => [q(slug), q(name), q(kind), i]));
out[out.length - 1] = out[out.length - 1].replace(/;$/, "\non conflict (slug) do nothing;");
insert("public.locations", ["slug", "name", "zone", "map_x", "map_y", "sort"], locations.map(([slug, name, zone, x, y], i) => [q(slug), q(name), q(zone), x, y, i]));
out[out.length - 1] = out[out.length - 1].replace(/;$/, "\non conflict (slug) do nothing;");

// ── people ──────────────────────────────────────────────────────────
const people = [...businesses.map((bz) => [bz.owner, ownerNames[bz.owner]]), ...buyers.map((l) => [l, titleCase(l)])];
const userId = (local) => uuidFrom("user:" + local);
insert("auth.users",
  ["id", "instance_id", "aud", "role", "email", "encrypted_password", "email_confirmed_at", "raw_user_meta_data", "raw_app_meta_data",
    "confirmation_token", "recovery_token", "email_change", "email_change_token_new", "created_at", "updated_at"],
  people.map(([local, name]) => [q(userId(local)), q("00000000-0000-0000-0000-000000000000"), q("authenticated"), q("authenticated"),
    q(email(local)), "''", ago(int(80, 120) * DAY), json({ full_name: name }), json({ provider: "email", providers: ["email"] }),
    "''", "''", "''", "''", ago(90 * DAY), ago(90 * DAY)]));
emit(`update public.profiles set is_demo = true, cu_verified = true where email like '%@${DEMO_DOMAIN}';`);

// ── businesses & products ───────────────────────────────────────────
const NEW_BUSINESSES = new Set(["glow-by-tolu", "chop-express", "trinkets-and-co"]);
const bizRows = [];
const productRows = [];
const imageRows = [];
const variantRows = [];
const productsByBiz = new Map();

for (const bz of businesses) {
  const id = uuidFrom("biz:" + bz.slug);
  bz.id = id;
  bz.ageMin = NEW_BUSINESSES.has(bz.slug) ? int(10, 25) * DAY : int(40, 75) * DAY;
  bizRows.push([q(id), q(userId(bz.owner)), q(bz.slug), q(bz.name), q(bz.tagline), q(bz.description), catRef(bz.category), locRef(bz.location),
    q(bz.sellerType), b(bz.verified), json(HOURS[bz.hours]), b(bz.delivery), q(bz.deliveryNote ?? null), "true", ago(bz.ageMin), ago(int(0, 5) * DAY)]);
  const list = [];
  bz.products.forEach((pr, idx) => {
    const pid = uuidFrom("product:" + pr.slug);
    const variants = (pr.variants?.values ?? []).map(([value, stock, delta], vi) => ({
      id: uuidFrom(`variant:${pr.slug}:${value}`), name: pr.variants.name, value, stock: stock ?? null, delta: (delta ?? 0) * 100, position: vi,
    }));
    const variantStock = variants.length && variants.every((v) => v.stock !== null) ? variants.reduce((n, v) => n + v.stock, 0) : null;
    const stock = pr.kind === "service" ? null : variantStock ?? pr.stock;
    const ageMin = Math.max(60, bz.ageMin - int(0, Math.floor(bz.ageMin * 0.9)) - idx * 30);
    const record = { ...pr, id: pid, stock, variants, ageMin, priceKobo: pr.price * 100, business: bz,
      allowsDelivery: bz.delivery, image: pr.images[0] ? imageUrl(pr.images[0]) : null };
    list.push(record);
    productRows.push([q(pid), q(id), q(pr.slug), q(pr.kind), q(pr.title), q(pr.description), catRef(pr.category ?? bz.category),
      record.priceKobo, pr.compareAt ? pr.compareAt * 100 : "null", q(pr.condition), stock === null ? "null" : stock, q("active"),
      locRef(bz.location), "true", b(bz.delivery), "true", ago(ageMin), ago(Math.min(ageMin, int(0, 10) * DAY))]);
    pr.images.forEach((key, pos) => imageRows.push([q(uuidFrom(`img:${pr.slug}:${pos}`)), q(pid), q(imageUrl(key)), pos, "true"]));
    variants.forEach((v) => variantRows.push([q(v.id), q(pid), q(v.name), q(v.value), v.stock === null ? "null" : v.stock, v.delta, v.position, "true"]));
  });
  productsByBiz.set(bz.slug, list);
}
insert("public.businesses", ["id", "owner_id", "slug", "name", "tagline", "description", "category_id", "location_id", "seller_type",
  "verified", "hours", "offers_delivery", "delivery_note", "is_demo", "created_at", "updated_at"], bizRows);
insert("public.products", ["id", "business_id", "slug", "kind", "title", "description", "category_id", "price_kobo", "compare_at_kobo",
  "condition", "stock", "status", "pickup_location_id", "allows_pickup", "allows_delivery", "is_demo", "created_at", "updated_at"], productRows);
insert("public.product_images", ["id", "product_id", "path", "position", "is_demo"], imageRows);
insert("public.product_variants", ["id", "product_id", "name", "value", "stock", "price_delta_kobo", "position", "is_demo"], variantRows);

// ── orders, items, events, reviews ──────────────────────────────────
const STATUS_WEIGHTS = [["completed", 80], ["cancelled", 5], ["pending", 5], ["confirmed", 4], ["preparing", 3], ["ready", 3]];
const pickStatus = () => {
  let r = rand() * 100;
  for (const [s, w] of STATUS_WEIGHTS) { if ((r -= w) < 0) return s; }
  return "completed";
};
const RATINGS = [[5, 55], [4, 30], [3, 10], [2, 4], [1, 1]];
const pickRating = () => {
  let r = rand() * 100;
  for (const [s, w] of RATINGS) { if ((r -= w) < 0) return s; }
  return 5;
};
const near = (r) => Math.min(5, Math.max(1, r + pick([-1, 0, 0, 0, 1])));
const textPool = (pr, rating) => {
  const pools = rating >= 4 ? reviewTexts : mixedReviewTexts;
  return pr.kind === "service" ? pools.service : pr.business.category === "food" ? pools.food : pools.product;
};

const orderRows = [], itemRows = [], eventRows = [], reviewRows = [];
const orderCount = new Map();
// Popular businesses get more orders.
const weighted = businesses.flatMap((bz) => Array(bz.verified ? 3 : 1).fill(bz));

for (let n = 0; n < 160; n++) {
  const bz = pick(weighted);
  const products = productsByBiz.get(bz.slug);
  const first = pick(products);
  const lines = [first];
  if (chance(0.25)) {
    const second = pick(products);
    if (second !== first) lines.push(second);
  }
  const oldestAllowed = Math.min(...lines.map((l) => l.ageMin), 60 * DAY);
  const placedAgo = int(90, Math.max(120, oldestAllowed - 30));
  const status = pickStatus();
  const delivery = bz.delivery && chance(0.4);
  const fulfilment = delivery ? "delivery" : "pickup";
  const buyer = pick(buyers);
  const orderId = uuidFrom("order:" + n);

  const chain = { pending: ["pending"], confirmed: ["pending", "confirmed"], preparing: ["pending", "confirmed", "preparing"],
    ready: ["pending", "confirmed", "preparing", delivery ? "out_for_delivery" : "ready_for_pickup"],
    completed: ["pending", "confirmed", ...(chance(0.5) ? ["preparing"] : []), delivery ? "out_for_delivery" : "ready_for_pickup", "completed"],
    cancelled: ["pending", "cancelled"] }[status];
  // Recent orders stay in progress; old ones must be terminal.
  const effectiveAgo = ["completed", "cancelled"].includes(status) ? placedAgo : int(20, 600);
  let t = effectiveAgo;
  const times = {};
  chain.forEach((s, i) => {
    if (i > 0) t = Math.max(1, t - int(8, s === "completed" ? 600 : 120));
    times[s] = t;
    eventRows.push([q(uuidFrom(`event:${n}:${s}`)), q(orderId), q(s), q(userId(s === "pending" || (s === "completed" && chance(0.3)) ? buyer : bz.owner)), ago(t)]);
  });
  const finalStatus = chain[chain.length - 1];
  let subtotal = 0;
  const items = lines.map((pr) => {
    const variant = pr.variants.length ? pick(pr.variants) : null;
    const qty = pr.kind === "service" ? 1 : chance(0.2) ? 2 : 1;
    const unit = pr.priceKobo + (variant?.delta ?? 0);
    subtotal += unit * qty;
    return { pr, variant, qty, unit };
  });
  orderRows.push([q(orderId), q(userId(buyer)), q(bz.id), q(finalStatus), q(fulfilment), subtotal,
    finalStatus !== "cancelled" && finalStatus !== "pending" ? q(pick(["Hall reception, after 6pm.", "Call me when you're outside.", "At the stand beside the main entrance."])) : "null",
    times.confirmed !== undefined ? ago(times.confirmed) : "null",
    times.ready_for_pickup !== undefined ? ago(times.ready_for_pickup) : times.out_for_delivery !== undefined ? ago(times.out_for_delivery) : "null",
    times.completed !== undefined ? ago(times.completed) : "null", times.cancelled !== undefined ? ago(times.cancelled) : "null",
    "true", ago(effectiveAgo), ago(t)]);
  items.forEach(({ pr, variant, qty, unit }, i) => {
    itemRows.push([q(uuidFrom(`item:${n}:${i}`)), q(orderId), q(pr.id), variant ? q(variant.id) : "null", q(pr.title),
      variant ? q(`${variant.name}: ${variant.value}`) : "null", q(pr.image), unit, qty]);
    if (finalStatus !== "cancelled") orderCount.set(pr.id, (orderCount.get(pr.id) ?? 0) + qty);
    if (finalStatus === "completed" && chance(0.7)) {
      const rating = pickRating();
      const sub = chance(0.5);
      reviewRows.push([q(uuidFrom(`review:${n}:${i}`)), q(orderId), q(pr.id), q(bz.id), q(userId(buyer)), rating,
        sub ? near(rating) : "null", sub ? near(rating) : "null", sub ? near(rating) : "null", sub ? near(rating) : "null",
        chance(0.6) ? q(pick(textPool(pr, rating))) : "null", "true", ago(Math.max(1, times.completed - int(30, 3 * DAY)))]);
    }
  });
}
insert("public.orders", ["id", "buyer_id", "business_id", "status", "fulfilment", "subtotal_kobo", "pickup_instructions",
  "confirmed_at", "ready_at", "completed_at", "cancelled_at", "is_demo", "created_at", "updated_at"], orderRows);
insert("public.order_items", ["id", "order_id", "product_id", "variant_id", "title_snapshot", "variant_snapshot", "image_snapshot",
  "unit_price_kobo", "quantity"], itemRows);
insert("public.order_events", ["id", "order_id", "status", "actor_id", "created_at"], eventRows);
insert("public.reviews", ["id", "order_id", "product_id", "business_id", "author_id", "rating", "quality", "communication", "accuracy",
  "fulfilment_rating", "body", "is_demo", "created_at"], reviewRows);

// ── conversations & messages ────────────────────────────────────────
const convRows = [], msgRows = [];
const convKeys = new Set();
for (let n = 0; n < 40; n++) {
  const bz = pick(businesses);
  const pr = chance(0.8) ? pick(productsByBiz.get(bz.slug)) : null;
  const buyer = pick(buyers);
  const key = `${buyer}|${bz.slug}|${pr?.slug ?? ""}`;
  if (convKeys.has(key)) continue;
  convKeys.add(key);
  const convId = uuidFrom("conv:" + key);
  const script = pick(conversationScripts);
  let t = int(60, 45 * DAY);
  const startedAgo = t;
  const replies = chance(0.9);
  const msgs = [];
  script.forEach((body, i) => {
    const fromBuyer = i % 2 === 0;
    if (!fromBuyer && !replies) return;
    if (i > 0) t = Math.max(1, t - (fromBuyer ? int(5, 30) : int(5, 240)));
    msgs.push([q(uuidFrom(`msg:${key}:${i}`)), q(convId), q(userId(fromBuyer ? buyer : bz.owner)), q(body), pr ? q(pr.id) : "null", "true", ago(t)]);
  });
  convRows.push([q(convId), q(userId(buyer)), q(bz.id), pr ? q(pr.id) : "null", "true", ago(startedAgo)]);
  msgRows.push(...msgs);
}
insert("public.conversations", ["id", "buyer_id", "business_id", "product_id", "is_demo", "created_at"], convRows);
insert("public.messages", ["id", "conversation_id", "sender_id", "body", "product_id", "is_demo", "created_at"], msgRows);

// ── popularity counters ─────────────────────────────────────────────
const counterRows = [];
for (const list of productsByBiz.values()) {
  for (const pr of list) {
    const orders = orderCount.get(pr.id) ?? 0;
    counterRows.push(`(${q(pr.id)}::uuid, ${orders}, ${orders * int(8, 25) + int(3, 40)})`);
  }
}
emit(`update public.products p set order_count = c.orders, view_count = c.views
  from (values\n  ${counterRows.join(",\n  ")}\n) as c(id, orders, views)
 where p.id = c.id;`);
emit("commit;");

writeFileSync(new URL("../seed.sql", import.meta.url), out.join("\n\n") + "\n");
console.log(`seed.sql: ${businesses.length} businesses, ${productRows.length} products, ${orderRows.length} orders, ` +
  `${reviewRows.length} reviews, ${convRows.length} conversations, ${msgRows.length} messages`);
